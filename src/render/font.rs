pub struct BitmapFont {
    texture: Texture2D,
}

impl BitmapFont {
    pub async fn new() -> Self {
        // Create a texture from font data
        // 16 characters per row, 6 rows = 96 characters (ASCII 32-127)
        let tex_width = 16 * 8; // 128 pixels
        let tex_height = 6 * 8; // 48 pixels

        let mut pixels = vec![0u8; tex_width * tex_height * 4]; // RGBA

        for char_idx in 0..96 {
            let char_row = char_idx / 16;
            let char_col = char_idx % 16;
            let char_x = char_col * 8;
            let char_y = char_row * 8;

            for row in 0..8 {
                let byte = FONT_DATA[char_idx * 8 + row];
                for col in 0..8 {
                    let pixel_x = char_x + col;
                    let pixel_y = char_y + row;
                    let pixel_idx = (pixel_y * tex_width + pixel_x) * 4;

                    // Check if bit is set (MSB is leftmost)
                    let bit_set = (byte >> (7 - col)) & 1 != 0;

                    if bit_set {
                        pixels[pixel_idx] = 255; // R
                        pixels[pixel_idx + 1] = 255; // G
                        pixels[pixel_idx + 2] = 255; // B
                        pixels[pixel_idx + 3] = 255; // A
                    } else {
                        pixels[pixel_idx] = 0; // R
                        pixels[pixel_idx + 1] = 0; // G
                        pixels[pixel_idx + 2] = 0; // B
                        pixels[pixel_idx + 3] = 0; // A (transparent)
                    }
                }
            }
        }

        let texture = Texture2D::from_rgba8(tex_width as u16, tex_height as u16, &pixels);
        texture.set_filter(FilterMode::Nearest);

        Self { texture }
    }

    /// Get the source rectangle for a character in the font texture
    fn get_char_rect(&self, c: char) -> Option<Rect> {
        let code = c as u32;
        if !(32..=127).contains(&code) {
            return None;
        }

        let idx = code - 32;
        let row = idx / 16;
        let col = idx % 16;

        Some(Rect::new((col * 8) as f32, (row * 8) as f32, 8.0, 8.0))
    }

    /// Draw a single character at the given position
    pub fn draw_char(&self, c: char, x: f32, y: f32, color: Color) {
        if let Some(src_rect) = self.get_char_rect(c) {
            draw_texture_ex(
                &self.texture,
                x,
                y,
                color,
                DrawTextureParams {
                    source: Some(src_rect),
                    ..Default::default()
                },
            );
        }
    }

    /// Draw a character with a shadow
    pub fn draw_char_with_shadow(
        &self,
        c: char,
        x: f32,
        y: f32,
        fg_color: Color,
        shadow_color: Color,
    ) {
        // Draw shadow first
        self.draw_char(c, x + SHADOW_OFFSET_X, y + SHADOW_OFFSET_Y, shadow_color);
        // Draw foreground
        self.draw_char(c, x, y, fg_color);
    }

    /// Draw a single character at the given position with scaling
    pub fn draw_char_scaled(&self, c: char, x: f32, y: f32, scale: f32, color: Color) {
        if let Some(src_rect) = self.get_char_rect(c) {
            draw_texture_ex(
                &self.texture,
                x,
                y,
                color,
                DrawTextureParams {
                    source: Some(src_rect),
                    dest_size: Some(vec2(8.0 * scale, 8.0 * scale)),
                    ..Default::default()
                },
            );
        }
    }

    /// Draw a character with a shadow, scaled
    pub fn draw_char_with_shadow_scaled(
        &self,
        c: char,
        x: f32,
        y: f32,
        scale: f32,
        fg_color: Color,
        shadow_color: Color,
    ) {
        let shadow_offset = scale; // Scale the shadow offset too
                                   // Draw shadow first
        self.draw_char_scaled(c, x + shadow_offset, y + shadow_offset, scale, shadow_color);
        // Draw foreground
        self.draw_char_scaled(c, x, y, scale, fg_color);
    }
}
